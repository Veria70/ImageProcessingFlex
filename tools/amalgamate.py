#!/usr/bin/env python3
"""Builds single_include/ipf/ipf.hpp: all ipf headers merged into one drop-in file.

Usage: python tools/amalgamate.py
Local includes ("..." relative to include/ipf) are inlined once, in dependency order;
system includes are kept as they are.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "include", "ipf")
OUT = os.path.join(ROOT, "single_include", "ipf", "ipf.hpp")
INCLUDE_RE = re.compile(r'^\s*#\s*include\s+"([^"]+)"\s*$')

seen = set()


def inline(path):
    path = os.path.normpath(path)
    if path in seen:
        return []
    seen.add(path)
    lines = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.strip() == "#pragma once" or line.startswith("// SPDX-License-Identifier") or line.startswith("// Copyright (c) 2026 Daniel"):
                continue
            m = INCLUDE_RE.match(line)
            if m:
                lines.extend(inline(os.path.join(os.path.dirname(path), m.group(1))))
            else:
                lines.append(line.rstrip("\n"))
    rel = os.path.relpath(path, SRC).replace(os.sep, "/")
    return [f"// ---- begin {rel} " + "-" * max(0, 70 - len(rel)), *lines, f"// ---- end {rel}", ""]


def main():
    body = inline(os.path.join(SRC, "ipf.hpp"))
    with open(os.path.join(ROOT, "LICENSE"), encoding="utf-8") as f:
        license_text = ["// " + line if line.strip() else "//" for line in f.read().strip().splitlines()]
    header = [
        "// ImageProcessingFlex (ipf) - single-header distribution.",
        "// Generated by tools/amalgamate.py from include/ipf; do not edit by hand.",
        "// SPDX-License-Identifier: MIT",
        "//",
        *license_text,
        "//",
        "// Third-party data and acknowledgements: see THIRD_PARTY_NOTICES.md in the repository",
        "// (Turbo colormap: Apache-2.0, Google LLC; JPEG decoder based in part on the work of the",
        "// Independent JPEG Group).",
        "#pragma once",
        "",
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(header + body) + "\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(seen)} headers, {sum(1 for _ in open(OUT, encoding='utf-8'))} lines)")


if __name__ == "__main__":
    main()
